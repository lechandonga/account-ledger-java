-- 账户表：version 列承载乐观锁
CREATE TABLE account (
    id         VARCHAR(64)  NOT NULL PRIMARY KEY,
    balance    BIGINT       NOT NULL,
    version    BIGINT       NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_account_balance_nonnegative CHECK (balance >= 0)
);

-- 流水表：request_id 唯一约束保证重复提交不会产生第二条流水
CREATE TABLE ledger_entry (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    VARCHAR(64)  NOT NULL REFERENCES account (id),
    type          VARCHAR(16)  NOT NULL,
    amount        BIGINT       NOT NULL,
    balance_after BIGINT       NOT NULL,
    request_id    VARCHAR(128) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_ledger_amount_positive CHECK (amount > 0),
    CONSTRAINT uk_ledger_request_id UNIQUE (request_id)
);

-- 游标分页索引：与 (account_id, id) 排序读取匹配
CREATE INDEX idx_ledger_account_id ON ledger_entry (account_id, id);
